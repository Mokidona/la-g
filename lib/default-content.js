const MAX_STRING = 20000;
const MAX_ITEMS = 100;

/* Приводит произвольный JSON к схеме: недостающие поля берутся из шаблона,
   лишние ключи отбрасываются, строки и массивы ограничиваются по размеру. */
function mergeContent(base, patch) {
  if (Array.isArray(base)) {
    if (!Array.isArray(patch)) return clone(base);
    const template = base[0];
    return patch
      .slice(0, MAX_ITEMS)
      .map((item) => mergeContent(template, item))
      .filter((item) => item !== undefined);
  }

  if (base && typeof base === 'object') {
    const source = patch && typeof patch === 'object' && !Array.isArray(patch) ? patch : {};
    const result = {};
    Object.keys(base).forEach((key) => {
      result[key] = mergeContent(base[key], source[key]);
    });
    return result;
  }

  if (typeof base === 'string') {
    return typeof patch === 'string' ? patch.slice(0, MAX_STRING) : base;
  }

  if (typeof base === 'boolean') {
    return typeof patch === 'boolean' ? patch : base;
  }

  if (typeof base === 'number') {
    return typeof patch === 'number' && Number.isFinite(patch) ? patch : base;
  }

  return patch === undefined ? base : patch;
}

function clone(value) {
  return JSON.parse(JSON.stringify(value));
}

module.exports = { defaultContent, mergeContent, clone };
